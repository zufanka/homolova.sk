/** Median of a numeric list, taking the upper element of an even-length list —
 *  the same convention the prototype used, so the published figures match. */
function median(xs: number[]): number {
	const v = xs.slice().sort((a, b) => a - b);
	return v.length ? v[Math.floor(v.length / 2)] : 0;
}

